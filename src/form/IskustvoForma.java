    private boolean ubaciRadnoIskustvo(RadnoIskustvo ri) {
        KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.DODAJISK, ri);
        komunikacija.Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        boolean uspeh=(boolean) so.getOdgovor();
        return uspeh;
    }
     private boolean obrisiRadnoIskustvo(RadnoIskustvo ri) {
        KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.OBRISIISK, ri);
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        boolean uspeh=(boolean) so.getOdgovor();
        return uspeh;
    }
     private boolean promeniRadnoIskustvo(RadnoIskustvo ri) {
        ri.setRadnoMesto(jTextField1.getText());
        
        boolean provera=proveriRadnoIskustvo(ri);
        if(!provera){
            return provera;
        }
        KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.IZMENIISK, ri);
        
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        boolean uspeh=(boolean) so.getOdgovor();
        return uspeh;
    }

    private boolean proveriRadnoIskustvo(RadnoIskustvo ri) {
        return true;
    }

    private void vratiListuRadnoIskustvo(Object kriterijumRukovodilacKooperacije, List<RadnoIskustvo> pom) {
        List<Object>params=(List<Object>) kriterijumRukovodilacKooperacije;
        String radnoMesto=(String) params.get(0);
        pom=new ArrayList<>();
        for (RadnoIskustvo iskustvo : iskustva) {
            if(iskustvo.getRadnoMesto().contains(radnoMesto)){
                pom.add(iskustvo);
            }
        }
        if(pom.isEmpty()){
            JOptionPane.showMessageDialog(this, "Sistem nije pronasao vrednosti po zadatom kriterijumu");
            return;
        }
        this.pom=pom;
        ModelTabeleIskustvo mtr=new ModelTabeleIskustvo(pom);
        jTable1.setModel(mtr);
    }
