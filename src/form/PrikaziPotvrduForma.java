    private void popuniTabelu() {
        KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.VRATISTA, p);
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        List<StavkaPotvrde>stavke=(List<StavkaPotvrde>) so.getOdgovor();
        KlijentskiZahtev kz2=new KlijentskiZahtev(Operacije.VRATIKUL, null);
        Komunikacija.getInstance().posaljiZahtev(kz2);
        ServerskiOdgovor so2=Komunikacija.getInstance().primiOdgovor();
        List<PoljoprivrednaKultura>kulture=(List<PoljoprivrednaKultura>) so2.getOdgovor();
        List<String>nazivi=new ArrayList<>();
        for (StavkaPotvrde stavkaPotvrde : stavke) {
            System.out.println(stavkaPotvrde.getIznos());
            for (PoljoprivrednaKultura poljoprivrednaKultura : kulture) {
                if(poljoprivrednaKultura.getIdKultura()==stavkaPotvrde.getIdKultura()){
                    nazivi.add(poljoprivrednaKultura.getNazivKulture());
                    break;
                }
            }
        }
        ModelTabelePrikaziStavku mts=new ModelTabelePrikaziStavku(stavke, nazivi,jezik);
        jTable1.setModel(mts);
    }
