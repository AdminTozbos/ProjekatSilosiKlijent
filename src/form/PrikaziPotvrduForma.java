    private void postaviStaticke(Potvrda p) {
        SimpleDateFormat format=new SimpleDateFormat("dd.MM.yyyy");
        jLabel2.setText(format.format(p.getDatumIzdavanja()));
        jLabel4.setText(format.format(p.getDatumVazenja()));
        jLabel6.setText(p.getUkupanIznos()+"");
       
        for (RukovodilacKooperacije rukovodilacKooperacije : rukovodioci) {
            if(rukovodilacKooperacije.getId()==p.getIdRukovodilac()){
                jLabel8.setText(rukovodilacKooperacije.getIme()+" "+rukovodilacKooperacije.getPrezime());
            }
        }
        if(p.getKoopFlag()==0){
            for (PoljoprivrednoPreduzece poljoprivrednoPreduzece : preduzeca) {
                if(poljoprivrednoPreduzece.getIdKooperant()==p.getIdKooperant()){
                    jLabel10.setText(poljoprivrednoPreduzece.getNazivKooperanta());
                }
            }
        }
        else{
            for (PoljoprivrednoGazdinstvo gazdinstvo : gazdinstva) {
                if(gazdinstvo.getIdKooperant()==p.getIdKooperant()){
                    jLabel10.setText(gazdinstvo.getNazivKooperanta());
                }
            }
        }

    }

