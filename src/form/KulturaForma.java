    private void kreirajPoljoprivrednaKultura(PoljoprivrednaKultura pk) {
        boolean ispravan=proveriKulturu(pk);
        if(ispravan){
            KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.DODAJKUL, pk);
            komunikacija.Komunikacija.getInstance().posaljiZahtev(kz);
            ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
            boolean uspeh=(boolean) so.getOdgovor();
            if(uspeh){
                JOptionPane.showMessageDialog(this, "Sistem je zapamtio kulturu");
            }
            else{
                JOptionPane.showMessageDialog(this, "Sistem nije zapamtio kulturu","Greska",JOptionPane.ERROR_MESSAGE);
            }
            return;
        }
        else{
            JOptionPane.showMessageDialog(this, "Uneli ste nedozvoljenu vrednost polja","Greska",JOptionPane.ERROR_MESSAGE);
        }
    }

    private boolean proveriKulturu(PoljoprivrednaKultura pk) {
        boolean ok=true;
        try {
            Double cena=Double.parseDouble(jTextField2.getText());
            Mesec mesec=Mesec.valueOf(jTextField3.getText());
        } catch (Exception e) {
            return false;
        }
       
        if(!pk.getNazivKulture().matches("[a-zA-Z ]+"))return false;
        return true;
    }

    private boolean obrisiPoljoprivrednaKultura(PoljoprivrednaKultura pk) {
        KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.OBRISIKUL, pk);
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        boolean uspeh=(boolean) so.getOdgovor();
        return uspeh;
    }

    private boolean promeniPoljoprivrednaKultura(PoljoprivrednaKultura pk) {
        try {
            pk.setNazivKulture(jTextField1.getText());
            pk.setCena(Double.parseDouble(jTextField2.getText()));
            pk.setMesecZetve(Mesec.valueOf(jTextField3.getText()));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Unos nije u ispravnom formatu","Greska",JOptionPane.ERROR_MESSAGE);
        }
        
        boolean provera=proveriKulturu(pk);
        if(!provera){
            return provera;
        }
        KlijentskiZahtev kz=new KlijentskiZahtev(Operacije.IZMENIKUL, pk);
        
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        boolean uspeh=(boolean) so.getOdgovor();
        return uspeh;
    }

    private void vratiListuPoljoprivrednaKultura(Object kriterijumPoljoprivrednaKultura, List<PoljoprivrednaKultura> pom) {
        List<Object>params=(List<Object>) kriterijumPoljoprivrednaKultura;
        String naziv=(String) params.get(0);
        String cena=(String) params.get(1);
        String mesec=(String) params.get(2);
        pom=new ArrayList<>();
        for (PoljoprivrednaKultura kultura : kulture) {
            if(kultura.getNazivKulture().contains(naziv)&&String.valueOf(kultura.getCena()).contains(cena)&&String.valueOf(kultura.getMesecZetve()).contains(mesec)){
                pom.add(kultura);
            }
        }
        if(pom.isEmpty()){
            JOptionPane.showMessageDialog(this, "Sistem nije pronasao vrednosti po zadatom kriterijumu");
            return;
        }
        this.pom=pom;
        ModelTabelaKultura mtr=new ModelTabelaKultura(pom);
        jTable1.setModel(mtr);
    }
